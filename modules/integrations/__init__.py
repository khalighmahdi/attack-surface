class SlackIntegration(ChatOpsBase):
    """Slack webhook / Bot integration."""

    def test_connection(self) -> bool:
        try:
            resp = self.session.post(self.webhook_url, json={"text": "Connection test"}, timeout=10)
            return resp.status_code == 200
        except Exception as e:
            logger.error("Slack test failed: %s", e)
            return False

    def send_findings(self, findings: List[Dict], metadata: Dict) -> Dict[str, Any]:
        critical_high = [f for f in findings if isinstance(f, dict) and f.get("severity") in ("critical", "high")]
        if not critical_high:
            return {"sent": 0, "skipped": "No critical/high findings"}

        target = metadata.get("target", "Unknown")
        blocks = [{
            "type": "header",
            "text": {"type": "plain_text", "text": f"🚨 Attack Surface Alert: {target}"}
        }, {
            "type": "section",
            "fields": [
                {"type": "mrkdwn", "text": f"*Scan:* {target}"},
                {"type": "mrkdwn", "text": f"*Time:* {datetime.now().strftime('%Y-%m-%d %H:%M UTC')}"},
                {"type": "mrkdwn", "text": f"*Critical/High:* {len(critical_high)}"},
                {"type": "mrkdwn", "text": f"*Total Findings:* {len(findings)}"}
            ]
        }]

        for f in critical_high[:5]:
            blocks.append({
                "type": "section",
                "text": {"type": "mrkdwn",
                         "text": f"*{f.get('title', f.get('type', 'Finding'))}* — {f.get('host', 'N/A')}\n"
                               f"Severity: *{f.get('severity', 'info').upper()}*\n"
                               f"{f.get('description', '')[:200]}"}
            })

        blocks.append({"type": "context", "elements": [{"type": "mrkdwn", "text": f"Attack Surface Scanner v{metadata.get('version', 'Unknown')}"}]})

        try:
            resp = self.session.post(self.webhook_url, json={"blocks": blocks}, timeout=15)
            return {"sent": 1 if resp.status_code == 200 else 0, "status": resp.status_code}
        except Exception as e:
            logger.error("Slack send failed: %s", e)
            return {"error": str(e), "sent": 0}


