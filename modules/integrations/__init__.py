class JiraIntegration(IntegrationBase):
    """Jira Cloud/Server integration for finding tracking."""

    def __init__(self, config: Dict[str, Any]):
        self.base_url = config.get("base_url", "").rstrip("/")
        self.email = config.get("email", "")
        self.api_token = config.get("api_token", "")
        self.project_key = config.get("project_key", "")
        self.issue_type = config.get("issue_type", "Bug")
        self.severity_priority = {
            "critical": "Highest",
            "high": "High",
            "medium": "Medium",
            "low": "Low",
            "info": "Lowest"
        }
        self.session = requests.Session()
        self.session.auth = (self.email, self.api_token)
        self.session.headers.update({"Accept": "application/json", "Content-Type": "application/json"})

    def test_connection(self) -> bool:
        try:
            resp = self.session.get(f"{self.base_url}/rest/api/2/myself", timeout=10)
            return resp.status_code == 200
        except Exception as e:
            logger.error("Jira connection test failed: %s", e)
            return False

    def send_findings(self, findings: List[Dict], metadata: Dict) -> Dict[str, Any]:
        results = {"created": [], "failed": []}
        target = metadata.get("target", "Unknown")

        for finding in findings:
            if not isinstance(finding, dict):
                continue

            severity = finding.get("severity", "info")
            priority = self.severity_priority.get(severity, "Medium")

            # Build description with evidence
            desc = f"*Target:* {target}\n"
            desc += f"*Host:* {finding.get('host', 'N/A')}\n"
            desc += f"*Type:* {finding.get('type', finding.get('title', 'Finding'))}\n"
            desc += f"*Severity:* {severity.upper()}\n\n"
            desc += f"*Description:*\n{finding.get('description', 'No description')}\n\n"
            if finding.get("evidence"):
                desc += f"*Evidence:*\n{{code}}{finding['evidence']}{{code}}\n\n"
            if finding.get("remediation"):
                desc += f"*Remediation:*\n{finding['remediation']}\n\n"
            desc += f"_Auto-generated by Attack Surface Scanner v{metadata.get('version', 'Unknown')}_"

            payload = {
                "fields": {
                    "project": {"key": self.project_key},
                    "summary": f"[{severity.upper()}] {finding.get('title', finding.get('type', 'Security Finding'))} on {target}",
                    "description": desc,
                    "issuetype": {"name": self.issue_type},
                    "priority": {"name": priority},
                    "labels": ["attack-surface", "security", severity, target.replace(".", "-")]
                }
            }

            try:
                resp = self.session.post(f"{self.base_url}/rest/api/2/issue", json=payload, timeout=30)
                if resp.status_code in (200, 201):
                    issue_key = resp.json().get("key")
                    results["created"].append({"finding": finding.get("title"), "issue": issue_key})
                    logger.info("Created Jira issue: %s", issue_key)
                else:
                    results["failed"].append({"finding": finding.get("title"), "error": resp.text})
                    logger.error("Jira create failed: %s", resp.text)
            except Exception as e:
                results["failed"].append({"finding": finding.get("title"), "error": str(e)})
                logger.error("Jira exception: %s", e)

        return results


