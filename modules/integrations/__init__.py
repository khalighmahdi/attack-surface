"""Integrations — Jira, GitHub, SIEM, ChatOps, RBAC.

Provides:
- Jira: Create issues from findings, sync status
- GitHub: Create issues/PRs, security advisories
- SIEM: Syslog, HTTP Event Collector (HEC), Elastic, Splunk
- ChatOps: Slack, Discord, Telegram, Mattermost
- RBAC: Role-based access control for team collaboration
"""
from __future__ import annotations

import json
import logging
import os
import requests
from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from datetime import datetime
from pathlib import Path
from typing import Any, Dict, List, Optional

logger = logging.getLogger("AttackSurface.Integrations")


# =============================================================================
# Base Integration Classes
# =============================================================================

class IntegrationBase(ABC):
    """Abstract base for all integrations."""

    @abstractmethod
    def test_connection(self) -> bool:
        """Test if integration is configured and reachable."""
        pass

    @abstractmethod
    def send_findings(self, findings: List[Dict], metadata: Dict) -> Dict[str, Any]:
        """Send findings to the integration target."""
        pass


@dataclass
class IntegrationConfig:
    """Base configuration for integrations."""
    enabled: bool = False
    name: str = ""
    config: Dict[str, Any] = field(default_factory=dict)


