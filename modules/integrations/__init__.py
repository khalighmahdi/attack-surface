class SIEMIntegration(IntegrationBase):
    """Base SIEM integration."""

    def __init__(self, config: Dict[str, Any]):
        self.config = config
        self.session = requests.Session()
        if config.get("token"):
            self.session.headers.update({"Authorization": f"Bearer {config['token']}"})


class SplunkHECIntegration(SIEMIntegration):
    """Splunk HTTP Event Collector."""

    def __init__(self, config: Dict[str, Any]):
        super().__init__(config)
        self.hec_url = config.get("hec_url", "").rstrip("/")
        self.token = config.get("token", "")
        self.index = config.get("index", "main")
        self.sourcetype = config.get("sourcetype", "attack_surface:json")
        self.session.headers.update({"Authorization": f"Splunk {self.token}"})

    def test_connection(self) -> bool:
        try:
            resp = self.session.get(f"{self.hec_url}/services/collector/health", timeout=10)
            return resp.status_code == 200
        except Exception as e:
            logger.error("Splunk HEC test failed: %s", e)
            return False

    def send_findings(self, findings: List[Dict], metadata: Dict) -> Dict[str, Any]:
        events = []
        for f in findings:
            if not isinstance(f, dict):
                continue
            event = {
                "time": datetime.now().timestamp(),
                "index": self.index,
                "sourcetype": self.sourcetype,
                "event": {**f, "scan_target": metadata.get("target"), "scan_version": metadata.get("version")}
            }
            events.append(event)

        try:
            resp = self.session.post(f"{self.hec_url}/services/collector", json=events, timeout=30)
            if resp.status_code == 200:
                return {"sent": len(events), "ack": resp.json()}
            return {"error": resp.text, "sent": 0}
        except Exception as e:
            logger.error("Splunk HEC send failed: %s", e)
            return {"error": str(e), "sent": 0}


class ElasticIntegration(SIEMIntegration):
    """Elasticsearch / Elastic Security."""

    def __init__(self, config: Dict[str, Any]):
        super().__init__(config)
        self.url = config.get("url", "").rstrip("/")
        self.index = config.get("index", "attack-surface-findings")
        self.api_key = config.get("api_key", "")
        if self.api_key:
            self.session.headers.update({"Authorization": f"ApiKey {self.api_key}"})

    def test_connection(self) -> bool:
        try:
            resp = self.session.get(f"{self.url}/_cluster/health", timeout=10)
            return resp.status_code == 200
        except Exception as e:
            logger.error("Elastic connection test failed: %s", e)
            return False

    def send_findings(self, findings: List[Dict], metadata: Dict) -> Dict[str, Any]:
        # Bulk API
        bulk_data = []
        for f in findings:
            if not isinstance(f, dict):
                continue
            doc = {**f, "scan_target": metadata.get("target"), "scan_version": metadata.get("version"),
                   "@timestamp": datetime.now().isoformat()}
            bulk_data.append({"index": {"_index": self.index}})
            bulk_data.append(doc)

        try:
            payload = "\n".join(json.dumps(d) for d in bulk_data) + "\n"
            resp = self.session.post(f"{self.url}/_bulk", data=payload,
                                     headers={"Content-Type": "application/x-ndjson"}, timeout=60)
            if resp.status_code == 200:
                return {"sent": len(findings), "errors": resp.json().get("errors", False)}
            return {"error": resp.text, "sent": 0}
        except Exception as e:
            logger.error("Elastic bulk send failed: %s", e)
            return {"error": str(e), "sent": 0}


