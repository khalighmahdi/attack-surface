class GitHubIntegration(IntegrationBase):
    """GitHub Issues / Security Advisories integration."""

    def __init__(self, config: Dict[str, Any]):
        self.token = config.get("token", "")
        self.owner = config.get("owner", "")
        self.repo = config.get("repo", "")
        self.use_advisories = config.get("use_advisories", False)
        self.session = requests.Session()
        self.session.headers.update({
            "Authorization": f"Bearer {self.token}",
            "Accept": "application/vnd.github+json",
            "Content-Type": "application/json"
        })

    def test_connection(self) -> bool:
        try:
            resp = self.session.get("https://api.github.com/user", timeout=10)
            return resp.status_code == 200
        except Exception as e:
            logger.error("GitHub connection test failed: %s", e)
            return False

    def send_findings(self, findings: List[Dict], metadata: Dict) -> Dict[str, Any]:
        results = {"created": [], "failed": []}
        target = metadata.get("target", "Unknown")

        for finding in findings:
            if not isinstance(finding, dict):
                continue

            severity = finding.get("severity", "info")

            title = f"[{severity.upper()}] {finding.get('title', finding.get('type', 'Security Finding'))} — {target}"
            body = f"## Security Finding from Attack Surface Scanner\n\n"
            body += f"**Target:** {target}\n"
            body += f"**Host:** {finding.get('host', 'N/A')}\n"
            body += f"**Type:** {finding.get('type', finding.get('title', 'Finding'))}\n"
            body += f"**Severity:** {severity.upper()}\n\n"
            body += f"### Description\n{finding.get('description', 'No description')}\n\n"
            if finding.get("evidence"):
                body += f"### Evidence\n```\n{finding['evidence']}\n```\n\n"
            if finding.get("remediation"):
                body += f"### Remediation\n{finding['remediation']}\n\n"
            body += f"---\n_Auto-generated by Attack Surface Scanner v{metadata.get('version', 'Unknown')} on {datetime.now().isoformat()}_"

            labels = ["security", "attack-surface", severity, target.replace(".", "-")]

            if self.use_advisories:
                # GitHub Security Advisory (private)
                payload = {
                    "summary": title,
                    "description": body,
                    "severity": severity.upper(),
                    "vulnerabilities": [{"package": {"name": target, "ecosystem": "web"}, "severity": severity.upper()}]
                }
                url = f"https://api.github.com/repos/{self.owner}/{self.repo}/security-advisories"
            else:
                # Regular Issue
                payload = {"title": title, "body": body, "labels": labels}
                url = f"https://api.github.com/repos/{self.owner}/{self.repo}/issues"

            try:
                resp = self.session.post(url, json=payload, timeout=30)
                if resp.status_code in (200, 201):
                    issue = resp.json()
                    results["created"].append({"finding": finding.get("title"), "url": issue.get("html_url"), "number": issue.get("number")})
                    logger.info("Created GitHub %s: #%s", "advisory" if self.use_advisories else "issue", issue.get("number"))
                else:
                    results["failed"].append({"finding": finding.get("title"), "error": resp.text})
                    logger.error("GitHub create failed: %s", resp.text)
            except Exception as e:
                results["failed"].append({"finding": finding.get("title"), "error": str(e)})
                logger.error("GitHub exception: %s", e)

        return results


