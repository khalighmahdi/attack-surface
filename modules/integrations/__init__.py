# RBAC — Role-Based Access Control
# =============================================================================

@dataclass
class Role:
    name: str
    permissions: List[str]
    description: str = ""


class RBACManager:
    """Role-based access control for team collaboration."""

    DEFAULT_ROLES = {
        "admin": Role("admin", ["*"], "Full access to all features"),
        "analyst": Role("analyst", ["scan:read", "scan:run", "report:read", "report:generate",
                                     "finding:read", "finding:comment", "integration:read"],
                        "Security analyst - can run scans and view reports"),
        "viewer": Role("viewer", ["scan:read", "report:read", "finding:read"],
                       "Read-only access to scan results"),
        "operator": Role("operator", ["scan:read", "scan:run", "finding:read", "finding:comment",
                                       "action_center:propose", "action_center:execute"],
                         "Can execute action center tools with approval"),
        "auditor": Role("auditor", ["scan:read", "report:read", "finding:read", "audit:read"],
                        "Compliance auditor - read access + audit logs")
    }

    def __init__(self, config_path: Optional[str] = None):
        self.config_path = Path(config_path) if config_path else Path(os.path.expanduser("~/.attack_surface/rbac.json"))
        self.roles: Dict[str, Role] = {}
        self.user_roles: Dict[str, List[str]] = {}  # user_id -> [role_names]
        self._load()

    def _load(self):
        if self.config_path.exists():
            try:
                data = json.loads(self.config_path.read_text())
                self.roles = {k: Role(**v) for k, v in data.get("roles", {}).items()}
                self.user_roles = data.get("user_roles", {})
            except Exception as e:
                logger.warning("Failed to load RBAC config: %s", e)
                self._reset_defaults()
        else:
            self._reset_defaults()

    def _reset_defaults(self):
        self.roles = self.DEFAULT_ROLES.copy()
        self.user_roles = {}
        self._save()

    def _save(self):
        self.config_path.parent.mkdir(parents=True, exist_ok=True)
        data = {
            "roles": {k: {"name": r.name, "permissions": r.permissions, "description": r.description}
                      for k, r in self.roles.items()},
            "user_roles": self.user_roles
        }
        self.config_path.write_text(json.dumps(data, indent=2))

    def has_permission(self, user_id: str, permission: str) -> bool:
        """Check if user has permission (supports wildcards)."""
        user_roles = self.user_roles.get(user_id, [])
        for role_name in user_roles:
            role = self.roles.get(role_name)
            if role:
                for perm in role.permissions:
                    if perm == "*" or perm == permission or self._match_wildcard(perm, permission):
                        return True
        return False

    def _match_wildcard(self, pattern: str, permission: str) -> bool:
        if pattern.endswith(":*"):
            prefix = pattern[:-1]
            return permission.startswith(prefix)
        return False

    def assign_role(self, user_id: str, role_name: str) -> bool:
        if role_name not in self.roles:
            return False
        if user_id not in self.user_roles:
            self.user_roles[user_id] = []
        if role_name not in self.user_roles[user_id]:
            self.user_roles[user_id].append(role_name)
            self._save()
        return True

    def revoke_role(self, user_id: str, role_name: str) -> bool:
        if user_id in self.user_roles and role_name in self.user_roles[user_id]:
            self.user_roles[user_id].remove(role_name)
            self._save()
            return True
        return False

    def create_role(self, name: str, permissions: List[str], description: str = "") -> bool:
        if name in self.roles:
            return False
        self.roles[name] = Role(name, permissions, description)
        self._save()
        return True


