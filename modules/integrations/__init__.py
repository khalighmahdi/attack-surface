class IntegrationManager:
    """Central manager for all integrations."""

    def __init__(self, config_path: Optional[str] = None):
        self.config_path = Path(config_path) if config_path else Path(os.path.expanduser("~/.attack_surface/integrations.json"))
        self.integrations: Dict[str, IntegrationBase] = {}
        self.rbac = RBACManager()
        self._load_config()

    def _load_config(self):
        if self.config_path.exists():
            try:
                config = json.loads(self.config_path.read_text())
                self._init_integrations(config)
            except Exception as e:
                logger.warning("Failed to load integrations config: %s", e)

    def _init_integrations(self, config: Dict):
        for name, cfg in config.items():
            if not cfg.get("enabled"):
                continue
            if name == "jira":
                self.integrations[name] = JiraIntegration(cfg)
            elif name == "github":
                self.integrations[name] = GitHubIntegration(cfg)
            elif name == "splunk_hec":
                self.integrations[name] = SplunkHECIntegration(cfg)
            elif name == "elastic":
                self.integrations[name] = ElasticIntegration(cfg)
            elif name == "slack":
                self.integrations[name] = SlackIntegration(cfg)
            elif name == "discord":
                self.integrations[name] = DiscordIntegration(cfg)
            elif name == "telegram":
                self.integrations[name] = TelegramIntegration(cfg)

    def test_all(self) -> Dict[str, bool]:
        return {name: integ.test_connection() for name, integ in self.integrations.items()}

    def dispatch_findings(self, findings: List[Dict], metadata: Dict, user_id: str = None) -> Dict[str, Any]:
        """Send findings to all enabled integrations (respects RBAC if user_id provided)."""
        results = {}
        for name, integ in self.integrations.items():
            # Check RBAC if user provided
            if user_id and not self.rbac.has_permission(user_id, f"integration:{name}:write"):
                results[name] = {"error": "Permission denied", "skipped": True}
                continue
            try:
                results[name] = integ.send_findings(findings, metadata)
            except Exception as e:
                results[name] = {"error": str(e)}
                logger.error("Integration %s failed: %s", name, e)
        return results


# Convenience function
def create_integration_manager(config_path: str = None) -> IntegrationManager:
    return IntegrationManager(config_path)